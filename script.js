const THEME_CLASSES = ["theme-home", "theme-resepsi", "theme-tasmiah", "theme-wisuda"];

let currentCategory = "resepsi";
let currentResepsiSub = "2hari";

const homeView = document.getElementById("homeView");
const detailView = document.getElementById("detailView");
const detailTag = document.getElementById("detailTag");
const detailTitle = document.getElementById("detailTitle");
const detailSubtitle = document.getElementById("detailSubtitle");
const resepsiSubTabs = document.getElementById("resepsiSubTabs");
const packageGrid = document.getElementById("packageGrid");
const categoryNotes = document.getElementById("categoryNotes");

function applyTheme(themeName) {
  document.body.classList.remove(...THEME_CLASSES);
  document.body.classList.add(themeName);
}

function renderCategory(categoryKey) {
  const cat = CATALOG[categoryKey];
  if (!cat) return;

  currentCategory = categoryKey;
  applyTheme(`theme-${categoryKey}`);

  homeView.classList.add("hidden");
  detailView.classList.remove("hidden");
  window.scrollTo({ top: 0, behavior: "smooth" });

  document.querySelectorAll(".mini-tab").forEach((tab) => {
    tab.classList.toggle("active", tab.dataset.selectCategory === categoryKey);
  });

  detailTag.textContent = cat.tag;
  detailTitle.textContent = cat.title;
  detailSubtitle.textContent = cat.subtitle;

  let list = [];
  if (cat.hasSubTabs) {
    resepsiSubTabs.classList.remove("hidden");
    document.querySelectorAll(".sub-tab").forEach((btn) => {
      btn.classList.toggle("active", btn.dataset.sub === currentResepsiSub);
    });
    list = cat.subGroups[currentResepsiSub] || [];
  } else {
    resepsiSubTabs.classList.add("hidden");
    list = cat.items || [];
  }

  packageGrid.innerHTML = list
    .map(
      (pkg) => `
      <article class="pkg-card ${pkg.featured ? "featured" : ""}">
        <div>
          <span class="pkg-badge">${pkg.badge}</span>
          <h3 class="pkg-name">${pkg.name}</h3>
          <div class="pkg-price">
            ${pkg.price}
            <span>${pkg.subPrice}</span>
          </div>
          <ul class="pkg-features">
            ${pkg.features.map((f) => `<li>${f}</li>`).join("")}
          </ul>
        </div>
        <button type="button" class="pkg-btn" data-open-pkg="${pkg.id}">Pilih &amp; Lihat Detail</button>
      </article>
    `
    )
    .join("");

  categoryNotes.innerHTML = `
    <h3>${cat.notesTitle}</h3>
    <ul>
      ${cat.notes.map((n) => `<li>${n}</li>`).join("")}
    </ul>
  `;
}

function showHome() {
  detailView.classList.add("hidden");
  homeView.classList.remove("hidden");
  applyTheme("theme-home");
  window.scrollTo({ top: 0, behavior: "smooth" });
}

function openBookingModal(pkgId) {
  const cat = CATALOG[currentCategory];
  if (!cat) return;

  const list = cat.hasSubTabs ? cat.subGroups[currentResepsiSub] : cat.items;
  const pkg = (list || []).find((item) => item.id === pkgId);
  if (!pkg) return;

  const modal = document.getElementById("bookingModal");
  const subLabel = cat.hasSubTabs
    ? currentResepsiSub === "2hari"
      ? " (Paket 2 - 2 Hari Acara)"
      : " (Paket 1 - 1 Hari Acara)"
    : "";

  document.getElementById("modalCategory").textContent = `${cat.title}${subLabel}`;
  document.getElementById("modalTitle").textContent = pkg.name;
  document.getElementById("modalPrice").textContent = pkg.price;
  document.getElementById("modalFeatures").innerHTML = pkg.features.map((f) => `<li>${f}</li>`).join("");
  document.getElementById("modalNote").textContent = cat.modalNote;

  const msg = `Halo Pink Project, saya tertarik booking ${cat.title}${subLabel} - ${pkg.name} (${pkg.price}).`;
  document.getElementById("waBookingLink").href = `https://wa.me/?text=${encodeURIComponent(msg)}`;

  modal.classList.add("open");
  modal.setAttribute("aria-hidden", "false");
}

function closeBookingModal() {
  const modal = document.getElementById("bookingModal");
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");
}

document.addEventListener("click", (e) => {
  const catTrigger = e.target.closest("[data-select-category]");
  if (catTrigger) {
    renderCategory(catTrigger.dataset.selectCategory);
    return;
  }

  const subTrigger = e.target.closest("[data-sub]");
  if (subTrigger) {
    currentResepsiSub = subTrigger.dataset.sub;
    renderCategory("resepsi");
    return;
  }

  const pkgTrigger = e.target.closest("[data-open-pkg]");
  if (pkgTrigger) {
    openBookingModal(pkgTrigger.dataset.openPkg);
  }
});

document.getElementById("backHomeBtn").addEventListener("click", showHome);
document.getElementById("closeModalBtn").addEventListener("click", closeBookingModal);
document.getElementById("closeModalBackdrop").addEventListener("click", closeBookingModal);
document.addEventListener("keydown", (e) => {
  if (e.key === "Escape") closeBookingModal();
});
